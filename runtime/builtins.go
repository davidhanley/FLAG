func foldNumericBuiltin(name string, op func(lhs, rhs Value) Value, args ...Value) Value {
	if len(args) < 2 {
		panic(name + " expects at least two arguments")
	}
	acc := args[0]
	for i := 1; i < len(args); i++ {
		acc = op(acc, args[i])
	}
	return acc
}
